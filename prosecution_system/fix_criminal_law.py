def chinese_to_arabic(cn: str) -> str:
    """将中文数字转换为阿拉伯数字"""
    mapping = {
        '一': '1', '二': '2', '三': '3', '四': '4', '五': '5',
        '六': '6', '七': '7', '八': '8', '九': '9', '十': '0',
        '百': '', '千': '', '零': ''
    }
    result = cn
    for k, v in mapping.items():
        result = result.replace(k, v)
    return result


def read_file(path: str) -> str:
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def find_article_text(content: str, article_num: str) -> tuple:
    """
    找到指定条文在正文中的位置范围 (start, end)
    article_num 如 "第一百六十五条"
    """
    start = content.find(article_num)
    if start < 0:
        return -1, -1

    # 找条文主体结束：下一条"第X条"或到达文件末尾
    end = content.find("\n第一百", start + 5)
    if end < 0:
        end = content.find("\n第", start + 5)
    if end < 0:
        end = len(content)

    return start, end


